#!/usr/bin/env node
/**
 * Compare CouchDB and PowerSync scalability results.
 *
 * Usage:
 *   node compare-results.js <couch-results-dir> <powersync-results-dir>
 *   node compare-results.js  # uses previous_results/4.3.0.json as CouchDB baseline
 *
 * Reads JTL/JSON result files from both suites and produces a side-by-side
 * markdown comparison report.
 */
import fs from 'fs';
import path from 'path';

const args = process.argv.slice(2);

function readJsonResults(filePath) {
  if (!fs.existsSync(filePath)) {
    return null;
  }
  return JSON.parse(fs.readFileSync(filePath, 'utf8'));
}

function parseJtlToJson(jtlPath) {
  // JTL files from JMeter aggregate results plugin are JSON
  if (!fs.existsSync(jtlPath)) {
    return null;
  }
  const content = fs.readFileSync(jtlPath, 'utf8').trim();
  // Try JSON first (aggregate report format)
  try {
    return JSON.parse(content);
  } catch (e) {
    // CSV JTL format — parse manually
    const lines = content.split('\n');
    const header = lines[0].split(',');
    const results = {};
    for (let i = 1; i < lines.length; i++) {
      const values = lines[i].split(',');
      const label = values[header.indexOf('label')] || 'sync';
      const elapsed = parseInt(values[header.indexOf('elapsed')] || '0');
      if (!results[label]) {
        results[label] = { samples: [], errors: 0 };
      }
      results[label].samples.push(elapsed);
      if (values[header.indexOf('success')] === 'false') {
        results[label].errors++;
      }
    }

    // Convert to standard format
    const output = {};
    for (const [label, data] of Object.entries(results)) {
      const sorted = data.samples.sort((a, b) => a - b);
      const sum = sorted.reduce((a, b) => a + b, 0);
      output[label] = {
        transaction: label,
        sampleCount: sorted.length,
        errorCount: data.errors,
        errorPct: (data.errors / sorted.length) * 100,
        meanResTime: sum / sorted.length,
        medianResTime: sorted[Math.floor(sorted.length / 2)],
        minResTime: sorted[0],
        maxResTime: sorted[sorted.length - 1],
        pct1ResTime: sorted[Math.floor(sorted.length * 0.9)],
        pct2ResTime: sorted[Math.floor(sorted.length * 0.95)],
        pct3ResTime: sorted[Math.floor(sorted.length * 0.99)],
        throughput: sorted.length / (sum / 1000),
      };
    }
    return output;
  }
}

function findResults(dir) {
  if (!dir) return null;
  // Look for .json first, then .jtl
  const files = fs.readdirSync(dir);
  const jsonFile = files.find(f => f.endsWith('.json'));
  if (jsonFile) return readJsonResults(path.join(dir, jsonFile));
  const jtlFile = files.find(f => f.endsWith('.jtl'));
  if (jtlFile) return parseJtlToJson(path.join(dir, jtlFile));
  return null;
}

function formatNum(n) {
  if (n === undefined || n === null) return 'N/A';
  return Number(n).toLocaleString('en-US', { maximumFractionDigits: 1 });
}

function delta(couch, ps) {
  if (!couch || !ps) return 'N/A';
  const pct = ((ps - couch) / couch * 100).toFixed(1);
  const sign = pct > 0 ? '+' : '';
  return `${sign}${pct}%`;
}

function generateReport(couchResults, psResults) {
  let report = '# CHT Scalability: CouchDB vs PostgreSQL+PowerSync\n\n';
  report += `Generated: ${new Date().toISOString()}\n\n`;

  // Initial sync comparison
  const couchSync = couchResults?.sync || couchResults?.Total;
  const psSync = psResults?.['powersync-sync'] || psResults?.Total;

  if (couchSync || psSync) {
    report += '## Initial Sync Comparison\n\n';
    report += '| Metric | CouchDB | PowerSync | Delta |\n';
    report += '|--------|---------|-----------|-------|\n';

    const metrics = [
      ['Samples', 'sampleCount'],
      ['Errors', 'errorCount'],
      ['Mean (ms)', 'meanResTime'],
      ['Median (ms)', 'medianResTime'],
      ['Min (ms)', 'minResTime'],
      ['Max (ms)', 'maxResTime'],
      ['P90 (ms)', 'pct1ResTime'],
      ['P95 (ms)', 'pct2ResTime'],
      ['P99 (ms)', 'pct3ResTime'],
      ['Throughput (ops/s)', 'throughput'],
    ];

    for (const [label, key] of metrics) {
      const c = couchSync?.[key];
      const p = psSync?.[key];
      report += `| ${label} | ${formatNum(c)} | ${formatNum(p)} | ${delta(c, p)} |\n`;
    }
    report += '\n';
  }

  // If no structured results, note it
  if (!couchSync && !psSync) {
    report += '## Results\n\nNo JTL/JSON result files found in the specified directories.\n';
    report += 'Run the suites first, then re-run this comparison.\n\n';
  }

  report += '---\n';
  report += 'Generated by `tests/scalability/compare-results.js`\n';

  return report;
}

// Main
const couchDir = args[0] || path.join(import.meta.dirname, 'previous_results');
const psDir = args[1];

let couchResults;
if (fs.existsSync(couchDir) && fs.statSync(couchDir).isDirectory()) {
  couchResults = findResults(couchDir);
} else if (fs.existsSync(couchDir)) {
  // Direct file path
  couchResults = readJsonResults(couchDir) || parseJtlToJson(couchDir);
}

let psResults = null;
if (psDir) {
  if (fs.statSync(psDir).isDirectory()) {
    psResults = findResults(psDir);
  } else {
    psResults = readJsonResults(psDir) || parseJtlToJson(psDir);
  }
}

const report = generateReport(couchResults, psResults);
const outPath = path.join(import.meta.dirname, 'comparison_report.md');
fs.writeFileSync(outPath, report, 'utf8');
console.log(`Comparison report written to: ${outPath}`);
console.log(report);
